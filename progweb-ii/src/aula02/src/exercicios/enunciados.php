<h1>Exercícios 02/03</h1>

<h2>Condicionais</h2>

<ol>
  <li>
    Faça um programa que calcula e mostre o percentual de frequência de um estudante.
    Para isso, considere que 120 períodos correspondem a 100% da carga horária.
  </li>

  <li>
    Escreva um programa que verifica se um número é par ou ímpar.
  </li>

  <li>
    Crie um programa que verifica se um número inteiro é positivo, negativo ou zero.
  </li>

  <li>
    Faça um programa que escreve uma data por extenso, lendo os dados de três variáveis
    (representando uma data). Exemplo: 15/03/2023 → 15 de março de 2023.
  </li>
</ol>

<h2>Repetição</h2>

<ol start="5">
  <li>
    Faça um programa que escreva os números pares entre 2020 e 2.
    A saída deve exibir um número abaixo do outro.
  </li>

  <li>
    Faça um programa que execute um laço de repetição de 1 a 500 e exiba os números na tela.
    Caso o número seja divisível por 3 deve escrever Fizz, caso seja divisível por 5 deve escrever Buzz,
    caso seja divisível pelos dois divisores deve escrever FizzBuzz.
    Exemplo de saída: 1, 2, Fizz, 4, Buzz, Fizz, 7, 8, Fizz, Buzz, 11, Fizz, 13, 14, FizzBuzz…499.
    Ao exibir o último número, a vírgula não deve aparecer.
  </li>

  <li>
    Faça um programa que escreva os números primos entre 1 e 100.
  </li>

  <li>
    Desafio – Faça um programa que escreva os 10 primeiros números primos encontrados
    (lógica diferente do exercício anterior).
  </li>
</ol>