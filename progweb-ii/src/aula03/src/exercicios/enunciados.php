<h1>Exercícios 16/03</h1>

<h2>Testes condicionais. </h2>

<ol>

<li>
Faça um algoritmo que tenha duas variáveis que armazenam as horas trabalhadas por um
funcionário e o valor recebido por hora, e em seguida, calcule quanto será o salário desse
funcionário.
</li>

<li>
Faça um programa que armazena 3 números e exiba o maior deles.
</li>

<li>
Elabore um algoritmo que tenha duas variáveis: altura (h) e sexo de um indivíduo e em seguida,
calcule e mostre o peso ideal, conforme as fórmulas abaixo:
<ul>
<li>Para homens: (72.7 * h) - 58</li>
<li>Para mulheres: (62.1 * h) - 44.7</li>
</ul>
</li>

<li>
Faça um algoritmo que avalia o conteúdo de três variáveis do tipo inteiro (dia, mês e ano),
e em seguida escreve a data por extenso.
Exemplo: dia=10, mês=3, ano=2025 → 10 de março de 2025.
</li>

<li>
Faça um algoritmo que tenha 3 variáveis que representam 3 notas e calcule a média aritmética.
O algoritmo não deve considerar notas inválidas (valores negativos ou maiores que 10).
<br><br>
Exemplos:
<ul>
<li>7.5, 8, 8.5 → média = 8</li>
<li>8.5, 9.5, 11 → média = 9</li>
</ul>
</li>

<li>
Elabore um algoritmo que lê duas informações: peso e altura de um indivíduo e calcule
o Índice de Massa Corporal (IMC), apresentando o resultado na tela.
<br><br>
Exemplo: “Seu IMC é 22,3 sendo considerado normal”.
<br><br>
Fórmula do IMC:
<br>
IMC = peso / (altura²)
<img src="./../img/imc.png" alt="Fórmula do IMC" style="width: 250px; display: block;">
</li>

<li>
Chico tem 0,8 m e cresce 6 centímetros por ano, enquanto Juca tem 0,60 m e cresce
9 centímetros por ano. Construa um algoritmo que calcule e imprima quantos anos serão
necessários para que Juca seja maior que Chico.
</li>

<li>
Faça um programa que escreva os X primeiros números primos encontrados.
<br><br>
Exemplo: se X = 15, o algoritmo deverá escrever os 15 primeiros números primos.
</li>

</ol>