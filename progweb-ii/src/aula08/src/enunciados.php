    deve colocar um elemento do tipo select para permitir que o
    usuário escolha a operação (soma, subtração, multiplicação
    e divisão). Necessário validar as entradas.
  </li>

  <li>
    Elabore um formulário em HTML com dois campos de formulário
    (um para o peso e outro para a altura de uma pessoa) e um botão
    submit. Ao clicar em enviar, deve ser calculado e mostrado o Índice
    de Massa Corporal (IMC). O IMC é calculado da seguinte forma:
    imc = peso / (altura * altura).
  </li>

  <li>
    Elabore um formulário contendo cinco campos do tipo
    checkbox, cada um representando um esporte (ex: Natação,
    Futebol, Vôlei, etc..) e um botão do tipo submit. Crie uma
    página PHP que receba os dados através do método POST
    e imprima as modalidades selecionadas pelo usuário.
