<ul>
    <li><strong>1. Calculadora (0,5)</strong>
        <ul>
            <li>Elabore uma <strong>calculadora</strong> que:
                <ul>
                    <li>Recebe dados de um <strong>formulário</strong> através do método <strong>POST</strong>.</li>
                    <li>Exibe o resultado na tela.</li>
                    <li>Possui um <strong>elemento do tipo select</strong> para permitir que o usuário escolha a operação (soma, subtração, multiplicação e divisão).</li>
                    <li><strong>Validação</strong>: Garanta que os campos foram preenchidos corretamente.</li>
                </ul>
            </li>
        </ul>
    </li>

    <li><strong>2. Média do Estudante (0,5)</strong>
        <ul>
            <li>Elabore um <strong>formulário</strong> para calcular a <strong>média de um estudante</strong>, com os seguintes campos:
                <ul>
                    <li><strong>Nome</strong></li>
                    <li><strong>Nota 1</strong></li>
                    <li><strong>Nota 2</strong></li>
                    <li><strong>Nota 3</strong></li>
                </ul>
            </li>
            <li>Ao clicar em <strong>enviar</strong>, o sistema deve:
                <ul>
                    <li>Calcular a média e exibir a <strong>situação</strong> do aluno, que pode ser:
                        <ul>
                            <li>Média ≥ 7 → <strong>Aprovado</strong></li>
                            <li>Média entre 1,8 e 6,9 → <strong>Recuperação</strong></li>
                            <li>Média ≤ 1,7 → <strong>Reprovado</strong></li>
                        </ul>
                    </li>
                </ul>
            </li>
            <li><strong>Extras (obrigatório)</strong>:
                <ul>
                    <li>Exibir a maior nota.</li>
                    <li>Usar uma <strong>função</strong> para o cálculo da média.</li>
                    <li>As <strong>notas</strong> devem estar entre 0 e 10.</li>
                </ul>
            </li>
        </ul>
    </li>

    <li><strong>3. Pedido de Lanche (0,5)</strong>
        <ul>
            <li>Elabore um <strong>formulário</strong> para montagem de um <strong>pedido de lanche</strong>:
                <ul>
                    <li>O formulário deve permitir que o usuário informe <strong>seu nome</strong> e selecione, por meio de <strong>caixas de seleção (checkbox)</strong>, os itens desejados entre as seguintes opções:
                        <ul>
                            <li>Hambúrguer (R$ 15,00)</li>
                            <li>Batata frita (R$ 10,00)</li>
                            <li>Refrigerante (R$ 8,00)</li>
                            <li>Sobremesa (R$ 12,00)</li>
                        </ul>
                    </li>
                </ul>
            </li>
            <li><strong>Funcionalidades</strong>:
                <ul>
                    <li>O sistema deve calcular o <strong>valor total</strong> dos itens selecionados e aplicar <strong>5% de desconto</strong> caso a forma de pagamento escolhida seja <strong>dinheiro</strong>.</li>
                    <li>Ao final, exiba um <strong>resumo</strong> com:
                        <ul>
                            <li>Nome do cliente</li>
                            <li>Itens escolhidos</li>
                            <li>Valor total</li>
                            <li>Desconto (se houver)</li>
                            <li>Valor final da compra.</li>
                        </ul>
                    </li>
                </ul>
            </li>
            <li><strong>Validação</strong>:
                <ul>
                    <li>Verificar se <strong>pelo menos um item foi selecionado</strong>.</li>
                    <li>Verificar se <strong>o nome foi informado</strong>.</li>
                </ul>
            </li>
        </ul>
    </li>

    <li><strong>4. Análise de Hábitos Diários (0,5)</strong>
        <ul>
            <li>Elabore um <strong>formulário</strong> para análise de <strong>hábitos diários</strong>:
                <ul>
                    <li>O formulário deve permitir que o usuário informe <strong>seu nome</strong> e selecione, por meio de <strong>caixas de seleção (checkbox)</strong>, os hábitos que ele pratica regularmente entre as seguintes opções:
                        <ul>
                            <li>Beber água</li>
                            <li>Praticar exercícios físicos</li>
                            <li>Dormir bem</li>
                            <li>Alimentar-se de forma saudável</li>
                            <li>Evitar uso excessivo de celular</li>
                        </ul>
                    </li>
                </ul>
            </li>
            <li><strong>Funcionalidades</strong>:
                <ul>
                    <li>O sistema deve contar quantos hábitos foram selecionados e <strong>classificar o estilo de vida</strong> do usuário conforme a quantidade:
                        <ul>
                            <li>0 a 1 hábito → estilo de vida <strong>“não saudável”</strong></li>
                            <li>2 a 3 hábitos → estilo de vida <strong>“moderado”</strong></li>
                            <li>4 ou mais hábitos → estilo de vida <strong>“saudável”</strong></li>
                        </ul>
                    </li>
                </ul>
            </li>
            <li>Ao final, exiba:
                <ul>
                    <li>O <strong>nome</strong> do usuário.</li>
                    <li>Os <strong>hábitos selecionados</strong>.</li>
                    <li>A <strong>classificação obtida</strong>.</li>
                </ul>
            </li>
            <li><strong>Validação</strong>:
                <ul>
                    <li>Verificar se <strong>pelo menos um hábito foi selecionado</strong>.</li>
                    <li>Verificar se <strong>o nome foi informado</strong>.</li>
                </ul>
            </li>
        </ul>
    </li>
</ul>